local TS = 32
local function t2p(col, row, dy)
  return (col - 1) * TS, (row - 1) * TS + (dy or 0)
end
local spawn_x, spawn_y = t2p(3, 12)

return {
  tilesize    = TS,
  spawn_index = 2,
  layers = {
    {
      name       = "cliff",
