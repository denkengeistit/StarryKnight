-- outskirts_01: a 50x18 tile demo zone (1600x576 world pixels at tilesize 32).
-- Three parallel z-depth slices. The player spawns in 'mid'.
--
-- Each layer is described as a multi-line string:
--   '#' = solid tile
--    .  = empty (anything that isn't '#')
--
-- The terrain is intentionally staggered so simply running right in any one
-- layer hits a wall or pit at some point; the player has to weave through
-- depths to make it across.
--
--   pinch 1 (cols 13-17): mid has a pit, far has a wall, near is clear.
--   pinch 2 (cols 24-27): mid has a wall, near has a wall, far is clear.
--   pinch 3 (cols 36-42): mid + near have pits, far is clear.
--
-- 50 columns wide:
--          1111111111222222222233333333334444444444445
-- 12345678901234567890123456789012345678901234567890

