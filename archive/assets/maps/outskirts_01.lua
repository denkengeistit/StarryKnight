-- Helper to make entity world coords from tile coords (1-indexed).
local TS = 32
local function t2p(col, row, dy)
  return (col - 1) * TS, (row - 1) * TS + (dy or 0)
end

-- Spawn at column 3, row 12 (player falls to ground at row 14 and lands).
local spawn_x, spawn_y = t2p(3, 12)

return {
  tilesize = TS,
  layers = {
    far = {
      tiles = far,
      tile_color = { 0.32, 0.32, 0.45 },
      bg_color   = { 0.05, 0.07, 0.14 },
      parallax   = 0.70,
      dim        = 0.45,
      spawn      = { x = spawn_x, y = spawn_y },
      entities = {
        -- A skeleton patrolling between the two pinches
        { type = "skeleton", x = (30 - 1) * TS, y = (12 - 1) * TS, lvl = 1 },
        -- XP shard reward for venturing into 'far'
        { type = "xp",       x = (44 - 1) * TS + 8, y = (13 - 1) * TS + 8 },
      },
    },
    mid = {
      tiles = mid,
      tile_color = { 0.58, 0.55, 0.52 },
      bg_color   = { 0.10, 0.10, 0.13 },
      parallax   = 1.00,
      dim        = 0.50,
      spawn      = { x = spawn_x, y = spawn_y },
      entities = {
        { type = "skeleton", x = ( 9 - 1) * TS, y = (12 - 1) * TS, lvl = 1 },
        { type = "skeleton", x = (22 - 1) * TS, y = (12 - 1) * TS, lvl = 1 },
        { type = "skeleton", x = (47 - 1) * TS, y = (12 - 1) * TS, lvl = 2 },
      },
    },
    near = {
      tiles = near,
      tile_color = { 0.40, 0.58, 0.42 },
      bg_color   = { 0.06, 0.10, 0.07 },
      parallax   = 1.30,
      dim        = 0.55,
      spawn      = { x = spawn_x, y = spawn_y },
      entities = {
        -- Heal orb hidden behind the first pinch (reward for taking 'near')
        { type = "heal", x = (20 - 1) * TS + 8, y = (13 - 1) * TS + 8 },
        -- A skeleton guarding the exit
        { type = "skeleton", x = (46 - 1) * TS, y = (12 - 1) * TS, lvl = 1 },
      },
    },
  },
}
